export type IconName = keyof typeof ICONS;

// sm is the size in buttons and links (the Back link in Figma), md is the size the set is drawn at.
const ICON_SIZES = {
  sm: "size-4.5",
  md: "size-6",
} as const;

export type IconSize = keyof typeof ICON_SIZES;

type IconProps = Omit<SVGProps<SVGSVGElement>, "children"> & {
  name: IconName;
  size?: IconSize;
};

/**
 * Hidden from screen readers by default, because an icon is almost always next to text
 * that says the same. An icon that stands alone needs a label on the button around it.
 */
export function Icon({ name, size = "md", className, ...props }: IconProps) {
  return (
    <svg
      viewBox="0 0 24 24"
      fill="none"
      aria-hidden="true"
      className={["shrink-0", ICON_SIZES[size], className]
        .filter(Boolean)
        .join(" ")}
      {...props}
    >
      {ICONS[name]}
    </svg>
  );
}
